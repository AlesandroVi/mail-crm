"""Base de datos del CRM.

Funciona con dos motores usando el mismo codigo:
  - SQLite: un archivo local (crm.db). Es lo que se usa en tu PC.
  - Postgres: una base en la nube. Se usa cuando existe la variable DATABASE_URL.

Tablas:
  contacts  -> una fila por persona/remitente (el corazon de un CRM)
  emails    -> cada mail recibido, enlazado a su contacto
  decisions -> lo que la app decidio hacer con cada mail y por que
  rules     -> tus reglas por remitente
  drafts    -> el borrador de respuesta de cada mail (como mucho uno por mail)
  settings  -> ajustes sueltos de la app
"""
import sqlite3
from pathlib import Path

from . import config

# Las dos unicas diferencias de esquema entre motores: como se numera el id
# y como se pide la fecha actual.
_DIALECTOS = {
    "sqlite": {"pk": "INTEGER PRIMARY KEY", "ahora": "(datetime('now'))"},
    "postgres": {
        "pk": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "ahora": "(to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))",
    },
}

ESQUEMA = """
CREATE TABLE IF NOT EXISTS contacts (
    id           {pk},
    email        TEXT NOT NULL UNIQUE,
    name         TEXT,
    first_seen   TEXT NOT NULL,
    last_seen    TEXT NOT NULL,
    email_count  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS emails (
    id           {pk},
    gmail_id     TEXT NOT NULL UNIQUE,
    thread_id    TEXT,
    contact_id   INTEGER NOT NULL REFERENCES contacts(id),
    subject      TEXT,
    snippet      TEXT,
    body         TEXT,
    received_at  TEXT NOT NULL,
    labels       TEXT,
    is_unread    INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS decisions (
    id          {pk},
    email_id    INTEGER NOT NULL REFERENCES emails(id),
    category    TEXT NOT NULL,
    action      TEXT NOT NULL,
    reason      TEXT,
    model       TEXT,
    dry_run     INTEGER NOT NULL DEFAULT 1,
    applied     INTEGER NOT NULL DEFAULT 0,
    created_at  TEXT NOT NULL DEFAULT {ahora}
);

CREATE TABLE IF NOT EXISTS rules (
    id          {pk},
    pattern     TEXT NOT NULL UNIQUE,
    action      TEXT NOT NULL,
    note        TEXT,
    created_at  TEXT NOT NULL DEFAULT {ahora}
);

CREATE TABLE IF NOT EXISTS settings (
    name   TEXT PRIMARY KEY,
    value  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS drafts (
    id              {pk},
    email_id        INTEGER NOT NULL UNIQUE REFERENCES emails(id),
    body            TEXT NOT NULL,
    model           TEXT,
    gmail_draft_id  TEXT,
    created_at      TEXT NOT NULL DEFAULT {ahora}
);

CREATE INDEX IF NOT EXISTS idx_emails_contact ON emails(contact_id);
CREATE INDEX IF NOT EXISTS idx_decisions_email ON decisions(email_id);
"""


class ConexionPostgres:
    """Hace que una conexion de Postgres se use igual que una de SQLite.

    El resto del archivo escribe las consultas una sola vez, con "?" para los
    valores; aca se traducen al formato de Postgres ("%s").
    """

    def __init__(self, url: str):
        import psycopg
        from psycopg.rows import dict_row

        # prepare_threshold=None: necesario para los "poolers" de conexiones (Supabase).
        # sslmode="require": si la conexion no puede ir cifrada, falla en vez de seguir sin cifrar.
        self._c = psycopg.connect(
            url, autocommit=True, row_factory=dict_row, prepare_threshold=None, sslmode="require"
        )
        self._tx = None

    def execute(self, sql: str, parametros=()):
        return self._c.execute(sql.replace("?", "%s"), tuple(parametros) or None)

    def executescript(self, sql: str) -> None:
        self._c.execute(sql)

    def __enter__(self):  # "with conn:" = transaccion, igual que en SQLite
        self._tx = self._c.transaction()
        self._tx.__enter__()
        return self

    def __exit__(self, *exc):
        return self._tx.__exit__(*exc)

    def close(self) -> None:
        self._c.close()


def leer_ajuste(conn, nombre: str, defecto: str = "") -> str:
    fila = conn.execute("SELECT value FROM settings WHERE name = ?", (nombre,)).fetchone()
    return fila["value"] if fila else defecto


def guardar_ajuste(conn, nombre: str, valor: str) -> None:
    with conn:
        conn.execute(
            "INSERT INTO settings (name, value) VALUES (?, ?) "
            "ON CONFLICT (name) DO UPDATE SET value = excluded.value",
            (nombre, valor),
        )


_esquema_listo: set[str] = set()


def motor() -> str:
    return "postgres" if config.DATABASE_URL else "sqlite"


def conectar(ruta: Path | str | None = None):
    """Abre la base (y crea las tablas si no existen) y devuelve la conexion.

    Si se pasa `ruta` siempre abre ese archivo SQLite; si no, usa Postgres
    cuando hay DATABASE_URL y el archivo local crm.db en caso contrario.
    """
    if ruta is None and config.DATABASE_URL:
        conn = ConexionPostgres(config.DATABASE_URL)
        if "postgres" not in _esquema_listo:  # una sola vez por arranque
            conn.executescript(ESQUEMA.format(**_DIALECTOS["postgres"]))
            _esquema_listo.add("postgres")
        return conn

    conn = sqlite3.connect(ruta or config.DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.executescript(ESQUEMA.format(**_DIALECTOS["sqlite"]))
    return conn


def mail_ya_guardado(conn: sqlite3.Connection, gmail_id: str) -> bool:
    fila = conn.execute("SELECT 1 FROM emails WHERE gmail_id = ?", (gmail_id,)).fetchone()
    return fila is not None


def guardar_mail(conn: sqlite3.Connection, mail: dict) -> bool:
    """Guarda un mail y crea/actualiza su contacto.

    `mail` es un dict con: gmail_id, thread_id, from_email, from_name, subject,
    snippet, body, received_at (ISO), labels (lista), is_unread (bool).
    Devuelve True si era nuevo, False si ya estaba guardado.
    """
    if mail_ya_guardado(conn, mail["gmail_id"]):
        return False

    with conn:  # transaccion: o se guarda todo o nada
        conn.execute(
            """
            INSERT INTO contacts (email, name, first_seen, last_seen, email_count)
            VALUES (?, ?, ?, ?, 1)
            ON CONFLICT(email) DO UPDATE SET
                name        = COALESCE(NULLIF(excluded.name, ''), contacts.name),
                first_seen  = CASE WHEN excluded.first_seen < contacts.first_seen
                                   THEN excluded.first_seen ELSE contacts.first_seen END,
                last_seen   = CASE WHEN excluded.last_seen > contacts.last_seen
                                   THEN excluded.last_seen ELSE contacts.last_seen END,
                email_count = contacts.email_count + 1
            """,
            (
                mail["from_email"].lower(),
                mail.get("from_name") or "",
                mail["received_at"],
                mail["received_at"],
            ),
        )
        contact_id = conn.execute(
            "SELECT id FROM contacts WHERE email = ?", (mail["from_email"].lower(),)
        ).fetchone()["id"]

        conn.execute(
            """
            INSERT INTO emails (gmail_id, thread_id, contact_id, subject, snippet,
                                body, received_at, labels, is_unread)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                mail["gmail_id"],
                mail.get("thread_id"),
                contact_id,
                mail.get("subject"),
                mail.get("snippet"),
                mail.get("body"),
                mail["received_at"],
                ",".join(mail.get("labels") or []),
                int(bool(mail.get("is_unread"))),
            ),
        )
    return True


def mails_sin_decision(conn: sqlite3.Connection, limite: int) -> list[sqlite3.Row]:
    """Mails que la IA todavia no clasifico (los mas nuevos primero)."""
    return conn.execute(
        """
        SELECT e.id, e.subject, e.snippet, e.body, c.email AS from_email, c.name AS from_name
        FROM emails e
        JOIN contacts c ON c.id = e.contact_id
        WHERE NOT EXISTS (SELECT 1 FROM decisions d WHERE d.email_id = e.id)
        ORDER BY e.received_at DESC
        LIMIT ?
        """,
        (limite,),
    ).fetchall()


def guardar_decision(
    conn: sqlite3.Connection,
    email_id: int,
    category: str,
    action: str,
    reason: str,
    model: str,
    dry_run: bool = True,
) -> None:
    with conn:
        conn.execute(
            "INSERT INTO decisions (email_id, category, action, reason, model, dry_run) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            (email_id, category, action, reason, model, int(dry_run)),
        )


def borrar_decisiones_simuladas(conn: sqlite3.Connection) -> int:
    """Borra las decisiones de simulacion que nunca se aplicaron, para volver a clasificar."""
    with conn:
        cur = conn.execute("DELETE FROM decisions WHERE dry_run = 1 AND applied = 0")
    return cur.rowcount


# --- Reglas por remitente -------------------------------------------------
# Una regla dice "con los mails de X, hace siempre Y" y manda sobre la IA.
# `pattern` puede ser un mail exacto (promo@tienda.com) o un dominio
# (tienda.com, que tambien cubre a.tienda.com).

def guardar_regla(conn: sqlite3.Connection, pattern: str, action: str, note: str = "") -> None:
    with conn:
        conn.execute(
            "INSERT INTO rules (pattern, action, note) VALUES (?, ?, ?) "
            "ON CONFLICT(pattern) DO UPDATE SET action = excluded.action, note = excluded.note",
            (pattern.strip().lower(), action, note),
        )


def borrar_regla(conn: sqlite3.Connection, pattern: str) -> bool:
    with conn:
        cur = conn.execute("DELETE FROM rules WHERE pattern = ?", (pattern.strip().lower(),))
    return cur.rowcount > 0


def listar_reglas(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    return conn.execute("SELECT pattern, action, note FROM rules ORDER BY pattern").fetchall()


def buscar_regla(reglas: list, email: str):
    """Devuelve la regla que corresponde a ese remitente, o None.

    Gana el mail exacto; si no hay, el dominio mas especifico.
    """
    email = email.lower()
    dominio = email.rsplit("@", 1)[-1]
    mejor = None
    for regla in reglas:
        patron = regla["pattern"]
        if patron == email:
            return regla
        if "@" not in patron and (dominio == patron or dominio.endswith("." + patron)):
            if mejor is None or len(patron) > len(mejor["pattern"]):
                mejor = regla
    return mejor


def reaplicar_reglas(conn: sqlite3.Connection) -> int:
    """Pone al dia las decisiones simuladas despues de cambiar una regla.

    - Si un mail ahora tiene regla, su decision pasa a ser la de la regla.
    - Si su decision venia de una regla que ya no existe, se borra y el mail
      queda pendiente para que lo clasifique la IA.
    Devuelve cuantas decisiones cambiaron. No toca decisiones ya aplicadas.
    """
    reglas = listar_reglas(conn)
    filas = conn.execute(
        """
        SELECT d.id, d.category, d.action, c.email
        FROM decisions d
        JOIN emails e ON e.id = d.email_id
        JOIN contacts c ON c.id = e.contact_id
        WHERE d.dry_run = 1 AND d.applied = 0
        """
    ).fetchall()
    cambios = 0
    with conn:
        for f in filas:
            regla = buscar_regla(reglas, f["email"])
            if regla is not None:
                if f["category"] != "regla" or f["action"] != regla["action"]:
                    conn.execute(
                        "UPDATE decisions SET category = 'regla', action = ?, reason = ?, model = 'regla' "
                        "WHERE id = ?",
                        (regla["action"], f"Regla tuya para {regla['pattern']}", f["id"]),
                    )
                    cambios += 1
            elif f["category"] == "regla":
                conn.execute("DELETE FROM decisions WHERE id = ?", (f["id"],))
                cambios += 1
    return cambios


def decisiones_aplicables(
    conn: sqlite3.Connection, acciones: tuple[str, ...], ids: list[int] | None = None
) -> list[sqlite3.Row]:
    """Decisiones vigentes, todavia no aplicadas, cuya accion cambia algo en Gmail."""
    marcas = ",".join("?" * len(acciones))
    sql = f"""
        SELECT d.id, d.action, e.gmail_id, e.subject
        FROM decisions d
        JOIN emails e ON e.id = d.email_id
        WHERE d.applied = 0
          AND d.action IN ({marcas})
          AND d.id = (SELECT MAX(id) FROM decisions WHERE email_id = d.email_id)
    """
    parametros: list = list(acciones)
    if ids is not None:
        if not ids:
            return []
        sql += f" AND d.id IN ({','.join('?' * len(ids))})"
        parametros += ids
    return conn.execute(sql, parametros).fetchall()


def decision_por_id(conn: sqlite3.Connection, decision_id: int):
    return conn.execute(
        "SELECT d.id, d.action, d.applied, e.gmail_id, e.subject "
        "FROM decisions d JOIN emails e ON e.id = d.email_id WHERE d.id = ?",
        (decision_id,),
    ).fetchone()


def marcar_aplicada(conn: sqlite3.Connection, decision_id: int, aplicada: bool) -> None:
    """Aplicada: ya se hizo en Gmail. Al deshacer vuelve a ser una simulacion."""
    with conn:
        conn.execute(
            "UPDATE decisions SET applied = ?, dry_run = ? WHERE id = ?",
            (int(aplicada), int(not aplicada), decision_id),
        )


def mails_con_decision(conn: sqlite3.Connection, limite: int = 300) -> list[sqlite3.Row]:
    """Cada mail con su ultima decision (o sin decision si esta pendiente)."""
    return conn.execute(
        """
        SELECT e.id AS email_id, e.subject, e.snippet, e.received_at,
               c.email AS from_email, c.name AS from_name,
               d.id AS decision_id, d.category, d.action, d.reason, d.model, d.dry_run, d.applied,
               b.body AS draft_body, b.gmail_draft_id
        FROM emails e
        JOIN contacts c ON c.id = e.contact_id
        LEFT JOIN decisions d ON d.id = (SELECT MAX(id) FROM decisions WHERE email_id = e.id)
        LEFT JOIN drafts b ON b.email_id = e.id
        ORDER BY e.received_at DESC
        LIMIT ?
        """,
        (limite,),
    ).fetchall()


# --- Borradores de respuesta ----------------------------------------------
# `gmail_draft_id` vacio = el texto solo existe en el panel.
# Con valor = ya esta guardado como borrador en Gmail.

def mail_para_responder(conn: sqlite3.Connection, email_id: int):
    """El mail recibido (con su remitente) y su borrador, si ya tiene uno."""
    return conn.execute(
        """
        SELECT e.id, e.gmail_id, e.subject, e.snippet, e.body,
               c.email AS from_email, c.name AS from_name,
               b.body AS draft_body, b.gmail_draft_id
        FROM emails e
        JOIN contacts c ON c.id = e.contact_id
        LEFT JOIN drafts b ON b.email_id = e.id
        WHERE e.id = ?
        """,
        (email_id,),
    ).fetchone()


def guardar_borrador(conn: sqlite3.Connection, email_id: int, texto: str, modelo: str | None = None) -> None:
    """Guarda (o reemplaza) el texto del borrador. Sin `modelo` conserva el que ya tenia."""
    with conn:
        conn.execute(
            "INSERT INTO drafts (email_id, body, model) VALUES (?, ?, ?) "
            "ON CONFLICT(email_id) DO UPDATE SET body = excluded.body, "
            "model = COALESCE(excluded.model, drafts.model)",
            (email_id, texto, modelo),
        )


def marcar_borrador_en_gmail(conn: sqlite3.Connection, email_id: int, gmail_draft_id: str | None) -> None:
    with conn:
        conn.execute("UPDATE drafts SET gmail_draft_id = ? WHERE email_id = ?", (gmail_draft_id, email_id))


def todos_los_contactos(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT email, name, email_count, first_seen, last_seen FROM contacts "
        "ORDER BY email_count DESC, last_seen DESC"
    ).fetchall()


def top_contactos(conn: sqlite3.Connection, limite: int = 10) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT email, name, email_count, last_seen FROM contacts "
        "ORDER BY email_count DESC, last_seen DESC LIMIT ?",
        (limite,),
    ).fetchall()
